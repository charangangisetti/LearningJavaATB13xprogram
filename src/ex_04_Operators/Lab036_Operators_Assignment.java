package ex_04_Operators;

public class Lab036_Operators_Assignment {
    public static void main(String[] args) {
        int age = 65;
        // int -> data type
        // age -> identifier
        // = -> Assignment operator
        // 65 -> Literal
        System.out.println(age);
        // RHV to the LH(So, "RHV to the LH" means assigning the value on the right side to the variable on the left.)
    }
}
